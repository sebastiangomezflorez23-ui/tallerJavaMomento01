public class Ejercicio16 {
    static void main() {
        /*16. Contar del 1 al 20
Usa un ciclo for para imprimir los números del 1 al 20, uno por línea.
Pista: Estructura: for (int i = 1; i <= 20; i++) { ... }. Es el ciclo 'contador' más básico de Java*/

        //ciclo for
        System.out.println("CONTANDO DEL 1 AL 20");
        for (int i = 1; i <= 20; i++) {
            System.out.println("Número: " + i);
        }

    }
}
